import { parse } from 'postcss';
import selectorParser from 'postcss-selector-parser';
import { assertResourceFreeStyleValue } from './style-source';

export const PAGE_STYLE_SOURCE_LIMIT = 12000;

const selectorOptions = { maxNestingDepth: 24, maxInputLength: PAGE_STYLE_SOURCE_LIMIT };
const allowedCombinators = new Set(['', '>', '+', '~']);
const rootStates = new Set([':hover', ':focus', ':focus-visible', ':focus-within', ':active']);
const pageValueFunctions = new Set(['var']);
const isRootAlias = (node: selectorParser.Node) =>
  (node.type === 'tag' && !node.namespace && /^(html|body)$/i.test(node.value)) ||
  (node.type === 'pseudo' && node.value.toLowerCase() === ':root' && !node.nodes.length);

function parseSelectors(selector: string, scope?: string) {
  if (/[\\\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]|\/\*/.test(selector))
    throw new Error('页面 CSS 选择器不能包含转义、控制字符或注释');
  const selectors = selectorParser().astSync(selector, selectorOptions);
  if (!selectors.nodes.length || /,\s*$/.test(selector))
    throw new Error('页面 CSS 选择器列表不能为空或以逗号结尾');
  return selectors.nodes.map((entry) => {
    const first = entry.first;
    if (!first || first.type === 'combinator' || entry.last?.type === 'combinator')
      throw new Error('页面 CSS 需要完整的选择器');
    const rooted = isRootAlias(first);
    entry.walk((node) => {
      if (
        node.type === 'nesting' ||
        (node.type === 'combinator' && !allowedCombinators.has(node.value.trim())) ||
        (node !== first && isRootAlias(node)) ||
        (node.type === 'pseudo' && /^:(?:scope|host|host-context)$/i.test(node.value))
      )
        throw new Error('页面 CSS 选择器不支持嵌套符号或跨页面选择');
    });
    if (rooted) {
      const rest = entry.nodes.slice(1);
      const boundary = rest.findIndex((node) => node.type === 'combinator');
      const rootModifiers = boundary < 0 ? rest : rest.slice(0, boundary);
      const firstCombinator = boundary < 0 ? '' : (rest[boundary]?.value ?? '').trim();
      if (
        rootModifiers.some(
          (node) =>
            node.type !== 'pseudo' ||
            node.nodes.length ||
            !rootStates.has(node.value.toLowerCase()),
        ) ||
        (firstCombinator !== '' && firstCombinator !== '>')
      )
        throw new Error('页面根选择器只支持根节点状态或页面内的子元素');
      if (scope)
        return `${scope}${rest
          .map((node) => node.toString())
          .join('')
          .trimEnd()}`;
    }
    return scope ? `${scope} ${entry.toString().trim()}` : entry.toString();
  });
}

function compilePageStyle(source: string, scope?: string) {
  if (source.length > PAGE_STYLE_SOURCE_LIMIT) throw new Error('页面 CSS 最多 12,000 个字符');
  const root = parse(source);
  const rules: string[] = [];
  for (const rule of root.nodes) {
    if (rule.type === 'comment') continue;
    if (rule.type !== 'rule') throw rule.error('页面 CSS 只支持样式规则，暂不支持 @ 规则');
    try {
      const selectors = parseSelectors(rule.raws.selector?.raw ?? rule.selector, scope);
      const declarations: string[] = [];
      for (const declaration of rule.nodes) {
        if (declaration.type === 'comment') continue;
        if (declaration.type !== 'decl' || !declaration.value.trim())
          throw new Error('样式块内只支持非空属性声明，不能嵌套规则');
        const property = declaration.prop;
        if (
          !/^(?:--[\w-]+|-?[a-z][\w-]*)$/i.test(property) ||
          /^(?:behavior|-moz-binding)$/i.test(property)
        )
          throw new Error(`不支持 CSS 属性 ${property}`);
        const value = declaration.raws.value?.raw ?? declaration.value;
        assertResourceFreeStyleValue(value, pageValueFunctions);
        declarations.push(
          `${property}: ${value.trim()}${declaration.important ? ' !important' : ''};`,
        );
      }
      if (declarations.length) rules.push(`${selectors.join(', ')} { ${declarations.join(' ')} }`);
    } catch (error) {
      throw rule.error(error instanceof Error ? error.message : String(error));
    }
  }
  return rules.join('\n');
}

export function assertPageStyleSource(source: string) {
  compilePageStyle(source);
}

/** The scope is generated by the renderer, never taken from a page schema. */
export function scopePageStyleSource(source: string, scope: string) {
  return compilePageStyle(source, scope);
}
